export function query<S extends string>(
  selector: S,
  root: ParentNode = document,
): S extends keyof AppElements ? AppElements[S] : HTMLElement {
  const element = root.querySelector(selector);
  if (!element) throw Error(`Missing application element: ${selector}`);
  return element as S extends keyof AppElements ? AppElements[S] : HTMLElement;
}
